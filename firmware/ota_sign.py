#!/usr/bin/env python3
"""OTA signing for the AButton firmware (WICED secure OTA: ECDSA P-256 over SHA-256).

The firmware only accepts OTA images signed with the owner's key. Format (matches
fw_upgrade_lib's ota_sec_fw_upgrade_verify): signed image = image + r(32, big-endian)
+ s(32, big-endian), the signature covering SHA-256(image). The public key is compiled
into the firmware as `Point ecdsa256_public_key = { x[8], y[8] }`, 32-bit words, least
significant first.

Don't use the SDK's wiced_tools/ecdsa256 Linux64 binaries: they are built with a 64-bit
`DWORD` and produce invalid signatures, and they draw keys and nonces from unseeded
rand(), which would make the private key recoverable.

  python3 firmware/ota_sign.py keygen                 # once; key in ~/.config/abutton/
  python3 firmware/ota_sign.py pubc -o ecdsa256_pub.c # the firmware's public key
  python3 firmware/ota_sign.py sign app.ota.bin       # -> app.ota.bin.signed
  python3 firmware/ota_sign.py verify app.ota.bin.signed
"""

import argparse
import os
import sys
from pathlib import Path

from cryptography.hazmat.primitives import hashes, serialization
from cryptography.hazmat.primitives.asymmetric import ec
from cryptography.hazmat.primitives.asymmetric.utils import decode_dss_signature, encode_dss_signature

DEFAULT_KEY = Path(os.environ.get("ABTN_OTA_KEY", Path.home() / ".config" / "abutton" / "ota_key.pem"))
SIG_LEN = 64


def keygen(path: Path, force: bool = False) -> ec.EllipticCurvePrivateKey:
    if path.exists() and not force:
        raise FileExistsError(f"{path} exists; refusing to replace the signing key (use --force)")
    key = ec.generate_private_key(ec.SECP256R1())
    path.parent.mkdir(parents=True, exist_ok=True)
    pem = key.private_bytes(serialization.Encoding.PEM, serialization.PrivateFormat.PKCS8,
                            serialization.NoEncryption())
    fd = os.open(path, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    with os.fdopen(fd, "wb") as fh:
        fh.write(pem)
    return key


def load_key(path: Path) -> ec.EllipticCurvePrivateKey:
    key = serialization.load_pem_private_key(path.read_bytes(), password=None)
    if not isinstance(key, ec.EllipticCurvePrivateKey) or key.curve.name != "secp256r1":
        raise ValueError(f"{path} is not a P-256 private key")
    return key


def _words(v: int) -> str:
    return ", ".join(f"0x{(v >> (32 * i)) & 0xFFFFFFFF:08x}" for i in range(8))


def public_c(pub: ec.EllipticCurvePublicKey) -> str:
    n = pub.public_numbers()
    return ("/* Generated by firmware/ota_sign.py: the OTA signing public key. */\n"
            "#include \"bt_types.h\"\n#include \"p_256_ecc_pp.h\"\n\n"
            "Point ecdsa256_public_key =\n{\n"
            f"    {{ {_words(n.x)} }},\n"
            f"    {{ {_words(n.y)} }},\n"
            "};\n")


def sign(image: bytes, key: ec.EllipticCurvePrivateKey) -> bytes:
    r, s = decode_dss_signature(key.sign(image, ec.ECDSA(hashes.SHA256())))
    return image + r.to_bytes(32, "big") + s.to_bytes(32, "big")


def verify(signed: bytes, pub: ec.EllipticCurvePublicKey) -> bool:
    if len(signed) <= SIG_LEN:
        return False
    body, sig = signed[:-SIG_LEN], signed[-SIG_LEN:]
    der = encode_dss_signature(int.from_bytes(sig[:32], "big"), int.from_bytes(sig[32:], "big"))
    try:
        pub.verify(der, body, ec.ECDSA(hashes.SHA256()))
        return True
    except Exception:
        return False


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--key", type=Path, default=DEFAULT_KEY, help=f"private key (default {DEFAULT_KEY})")
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("keygen")
    g.add_argument("--force", action="store_true")
    p = sub.add_parser("pubc")
    p.add_argument("-o", "--out", type=Path, required=True)
    s = sub.add_parser("sign")
    s.add_argument("image", type=Path)
    s.add_argument("-o", "--out", type=Path)
    v = sub.add_parser("verify")
    v.add_argument("signed", type=Path)
    args = ap.parse_args()

    if args.cmd == "keygen":
        keygen(args.key, args.force)
        print(f"wrote {args.key} (keep it private and backed up: it is the only key the firmware accepts)")
        return
    key = load_key(args.key)
    if args.cmd == "pubc":
        args.out.write_text(public_c(key.public_key()))
    elif args.cmd == "sign":
        out = args.out or args.image.with_name(args.image.name + ".signed")
        out.write_bytes(sign(args.image.read_bytes(), key))
        print(f"wrote {out}")
    elif args.cmd == "verify":
        ok = verify(args.signed.read_bytes(), key.public_key())
        print("signature OK" if ok else "signature INVALID")
        sys.exit(0 if ok else 1)


if __name__ == "__main__":
    main()
